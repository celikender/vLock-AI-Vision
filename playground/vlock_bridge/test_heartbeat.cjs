'use strict';
const assert = require('node:assert/strict');
const {HeartbeatMonitor} = require('./heartbeat.js');
const monitor = new HeartbeatMonitor();
const sample = (counter, session = 'session_01') => ({online: true, heartbeat_counter: counter, session_id: session, revision: 7});
assert.equal(monitor.status(0).waiting, true);
monitor.observe(sample(10), 0);
assert.equal(monitor.status(4999).online, true);
monitor.observe(sample(10), 4900);
assert.equal(monitor.status(5000).online, false, 'Duplicate heartbeats cannot extend liveness.');
monitor.observe(sample(11), 5100);
assert.equal(monitor.status(5100).online, true);
monitor.unavailable();
assert.equal(monitor.status(5101).online, false);
monitor.observe(sample(11), 5102);
assert.equal(monitor.status(5102).online, false, 'An unchanged cached sample cannot recover a failed connection.');
monitor.observe(sample(12), 5200);
assert.equal(monitor.status(5200).online, true);
monitor.observe(sample(0, 'session_02'), 5300);
assert.equal(monitor.status(5300).online, true, 'A restart has a new session and may reset its counter.');
monitor.observe(sample(0, 'session_02'), 10299);
assert.equal(monitor.status(10300).online, false);
monitor.observe(sample(-1), 10400);
assert.equal(monitor.status(10400).online, false);
monitor.observe({...sample(99), online: false}, 10500);
assert.equal(monitor.status(10500).online, false);
monitor.observe({...sample(100), offline_after_seconds: 30}, 10600);
assert.equal(monitor.status(35599).online, true, 'Longer pulse intervals advertise a longer watchdog.');
assert.equal(monitor.status(40600).online, false);
console.log('Heartbeat watchdog checks passed: timeout, duplicates, loss, recovery and restart.');
